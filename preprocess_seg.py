def filter_class_rgb(frame: np.ndarray, target_class_rgb: tuple, tolerance: int) -> np.ndarray:
    """
        Filter each RGB pixel of the frame and return a mask that covers all pixels (within a specified tolerance) of the target class. 
        Frame is a semantic segmentation representation of a scene
    """
    
    return np.all(np.abs(frame - target_class_rgb) <= tolerance, axis=-1)

