raw_data = np.load(raw_semantic)

background_mask_frames = []
edge_mask = []

for frame in raw_data:
    # run the frame through all the background classes first
    bg_curr_frame_masks = []
    for background_class in FILTERED_CLASS:
        class_index = background_class[1]
        class_mask = filter_class_type(frame, class_index)
        bg_curr_frame_masks.append(class_mask)
        
    # now run OR across all the background masks
    bg_curr_frame_masks = np.asarray(bg_curr_frame_masks, dtype=np.bool)
    # invert to save inverse mask - we want to preserve filtered features  
    bg_frame_mask = ~np.any(bg_curr_frame_masks, axis=0) 
    background_mask_frames.append(fill_mask(bg_frame_mask))
    
    # now generated a mask for the edge detection
    # this is combined with the ground-truth edges from semantic segmentation + canny edge    

    edge_curr_frame_masks = []
    for objects_edge in EDGE_CLASS:
        class_index = objects_edge[1]
        edge_curr_frame_masks.append(filter_class_type(frame, class_index))
        
    # now run OR across all the masks for the current frame
    edge_curr_frame_masks = np.asarray(edge_curr_frame_masks, dtype=np.bool)
    edge_frame_mask = np.any(edge_curr_frame_masks, axis=0) 
    
    edge_mask.append(fill_mask(edge_frame_mask))
        
save_mp4(np.asarray(background_mask_frames, dtype=np.uint8), output_seg, fps=20.0)
save_mp4(np.asarray(edge_mask, dtype=np.uint8), output_edge, fps=20.0)




