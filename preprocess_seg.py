def filter_class_type(frame: np.ndarray, class_type: int) -> np.ndarray:
    """
        Filter the input frame generated by CARLA (H,W) by the class_type supplied. Frame is a semantic segmentation representation of a scene in a ground truth format 
        generated by CARLA, where the value of each pixel in the input frame represents its ground truth semantic class. 
    
        frame: np.ndarry - Array of input shape (H,W)
        class_type: int - Class type to filter by (see CARLA docs for objects and their class types)
        
        Returns:
            np.ndarray - A boolean mask of shape (H,W) where only class_type is selected
    """
    return frame == class_type

def fill_mask(mask: np.ndarray, truth_label: tuple = (255,255,255), false_label: tuple = (0,0,0)) -> np.ndarray:
    """
        Convert a supplied boolean mask (H,W) into a 3D Array (H,W,3) where the final axis is the an RGB value of either truth_label or false_label
    """
    new_mask = np.repeat(mask[..., None], 3, axis=-1)
    frame = np.zeros_like(new_mask, dtype=np.uint8)
    
    frame[mask] = truth_label
    frame[~mask] = false_label
    
    return frame

def save_mp4(
    frames: np.ndarray,
    path: str,
    fps: float = 20.0,
) -> None:
    """Save uint8 BGR frames of shape (N, H, W, 3) as an MP4."""
    if frames.ndim != 4 or frames.shape[-1] != 3:
        raise ValueError("frames must have shape (N, H, W, 3)")

    frames = frames.astype(np.uint8, copy=False)
    _, height, width, _ = frames.shape

    writer = cv2.VideoWriter(
        path,
        cv2.VideoWriter_fourcc(*"mp4v"),
        fps,
        (width, height),  # OpenCV expects (W, H), not (H, W)
    )

    if not writer.isOpened():
        raise RuntimeError(f"Could not open video writer for {path}")

    for frame in frames:
        writer.write(frame)

    writer.release()

